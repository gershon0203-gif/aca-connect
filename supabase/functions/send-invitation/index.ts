// =============================================================================
// ACA Connect — Edge Function: `send-invitation`
// =============================================================================
// The ONLY place an invitation email is created/sent. Running server-side with
// the service-role key, it:
//
//   1. Verifies the caller's JWT and that the caller is a super_admin.
//   2. Creates the invitation row (token, role, optional member link, expiry).
//   3. Emails the invitee a link that returns them to /accept-invitation, where
//      the client calls the `accept_invitation` RPC — which independently
//      re-validates the token, the invited email and the granted role.
//
// The client never supplies a role, member id or permission: the function
// re-reads the caller's role from `user_roles` and the member link is validated
// by `accept_invitation` at redemption time.
//
// Deploy:
//   supabase functions deploy send-invitation
//
// Required secrets (Dashboard → Edge Functions → Secrets, or `supabase secrets set`):
//   SUPABASE_URL                (auto-injected as SUPABASE_URL)
//   SUPABASE_ANON_KEY           (auto-injected)
//   SUPABASE_SERVICE_ROLE_KEY   (auto-injected)
//   APP_URL                     e.g. https://app.acapozhichalur.org
//
// Email delivery requires SMTP to be configured in Supabase Auth
// (Dashboard → Authentication → Emails / SMTP). Without SMTP the function still
// creates the invitation and returns the shareable accept URL.
// =============================================================================

import { createClient } from 'npm:@supabase/supabase-js@2'

const CORS = {
  'Access-Control-Allow-Origin': '*',
  'Access-Control-Allow-Headers':
    'authorization, x-client-info, apikey, content-type',
  'Access-Control-Allow-Methods': 'POST, OPTIONS',
}

function json(body: unknown, status = 200): Response {
  return new Response(JSON.stringify(body), {
    status,
    headers: { ...CORS, 'Content-Type': 'application/json' },
  })
}

type Payload = {
  email?: string
  role?: 'super_admin' | 'member'
  memberCode?: string | null
}

Deno.serve(async (req) => {
  if (req.method === 'OPTIONS') return new Response('ok', { headers: CORS })
  if (req.method !== 'POST') return json({ error: 'Method not allowed' }, 405)

  const jwt = req.headers.get('Authorization')?.replace('Bearer ', '')
  if (!jwt) return json({ error: 'Missing authorization' }, 401)

  const supabaseUrl = Deno.env.get('SUPABASE_URL')!
  const anonKey = Deno.env.get('SUPABASE_ANON_KEY')!
  const serviceKey = Deno.env.get('SUPABASE_SERVICE_ROLE_KEY')!
  const appUrl = Deno.env.get('APP_URL') ?? ''

  // Verify the caller and confirm they are a super_admin.
  const asCaller = createClient(supabaseUrl, anonKey, {
    global: { headers: { Authorization: `Bearer ${jwt}` } },
    auth: { persistSession: false },
  })
  const { data: userData, error: userErr } = await asCaller.auth.getUser()
  if (userErr || !userData.user) return json({ error: 'Invalid session' }, 401)

  const { data: roleRow } = await asCaller
    .from('user_roles')
    .select('role, status')
    .eq('user_id', userData.user.id)
    .maybeSingle()
  if (!roleRow || roleRow.status !== 'active' || roleRow.role !== 'super_admin') {
    return json({ error: 'Only a super_admin may send invitations' }, 403)
  }

  let body: Payload
  try {
    body = await req.json()
  } catch {
    return json({ error: 'Invalid JSON body' }, 400)
  }

  const email = body.email?.trim().toLowerCase()
  const role = body.role ?? 'member'
  if (!email || !/^[^@\s]+@[^@\s]+\.[^@\s]+$/.test(email)) {
    return json({ error: 'A valid email address is required' }, 400)
  }
  if (!['super_admin', 'member'].includes(role)) {
    return json({ error: 'Invalid role' }, 400)
  }

  const admin = createClient(supabaseUrl, serviceKey, {
    auth: { persistSession: false },
  })

  // Create the invitation row. The token is generated by the database.
  const { data: invitation, error: inviteErr } = await admin
    .from('invitations')
    .insert({ email, role, member_code: body.memberCode || null })
    .select('id, token, email, role, member_code, expires_at')
    .single()
  if (inviteErr) return json({ error: inviteErr.message }, 500)

  const acceptUrl = appUrl
    ? `${appUrl.replace(/\/$/, '')}/accept-invitation?token=${invitation.token}`
    : `/accept-invitation?token=${invitation.token}`

  // Best-effort email. Failure to email does not invalidate the invitation.
  let emailed = false
  try {
    const { error } = await admin.auth.admin.inviteUserByEmail(email, {
      redirectTo: acceptUrl,
    })
    emailed = !error
  } catch {
    emailed = false
  }

  return json({ invitation, acceptUrl, emailed })
})
